"""Per-rule evidence from a nightly report: for each codewatch rule, the CVE pairs it found (verdict mode), the
fixed sides it still flagged, and its findings on public apps expected to be clean (benchmarks/clean-apps.json).
A reader can then tell a rule that is usually right from one that is usually noise.

    venv/bin/python benchmarks/rule_trust.py [NIGHTLY_DIR] > docs/rule-trust.md

NIGHTLY_DIR defaults to the newest ~/.cache/codewatch/nightly/DATE. Blind suites are never read.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
NIGHTLY = Path.home() / ".cache" / "codewatch" / "nightly"
PYTHON, JAVASCRIPT = "python", "javascript"
SUITES = ("cve-pairs-python", "cve-pairs-python-frontend", "cve-pairs-javascript")
RULE = re.compile(r"^codewatch:codewatch\.(python|js|templates)\.(?:web\.)?(?:template\.)?(.+)$")
FAMILY = {PYTHON: PYTHON, "templates": PYTHON, "js": JAVASCRIPT}


def rule_key(finding):
    """(language, short rule name) of a codewatch:... finding id, or None for registry rules."""
    m = RULE.match(finding.split("@")[0])
    return (FAMILY[m.group(1)], m.group(2)) if m else None


def cve_counts(results):
    """{(language, rule): [cases found, fixed sides still flagged]} over the open CVE suites."""
    counts = defaultdict(lambda: [0, 0])
    for suite in SUITES:
        path = results / f"{suite}.json"
        if not path.exists():
            continue
        for case in json.loads(path.read_text())["verdict"]["cases"]:
            for i, field in ((0, "by"), (1, "still_by")):
                for key in {rule_key(f) for f in case[field]} - {None}:
                    counts[key][i] += 1
    return counts


def app_counts(apps_txt, apps):
    """{(language, rule): [app, ...]} on the clean apps, one entry per finding; apps.txt lines are
    `app path line rule`."""
    counts = defaultdict(list)
    for line in apps_txt.read_text().splitlines():
        app, _, _, rule = line.split()[:4]
        if app in apps:
            counts[(apps[app], rule)].append(app)
    return counts


def table(nightly):
    apps = json.loads((HERE / "clean-apps.json").read_text())["apps"]
    cves, noise = cve_counts(nightly / "results"), app_counts(nightly / "apps.txt", apps)
    scanned = {lang: sum(1 for a in apps.values() if a == lang) for lang in (PYTHON, JAVASCRIPT)}
    lines = [f"# Rule trust: nightly {nightly.name}", "",
             ("Generated by `benchmarks/rule_trust.py`. For each codewatch taint or pattern rule: CVE fix pairs it found "
             "in verdict mode, fixed code it still flagged (each one a false alarm, unless the fix was incomplete), and "
             f"its findings on {scanned[PYTHON]} Python and {scanned[JAVASCRIPT]} JavaScript public apps expected "
             "to be clean (`benchmarks/clean-apps.json`)."), "",
             ("Every one of those apps was used to tune the rules, so the last column shows regressions, not precision. "
             "The blind app sets in the README are the untuned measure. Registry rules (Semgrep's, Bandit's) aren't "
             "listed. App findings are listed under the app's main language, so a JavaScript rule firing in a Python "
             "app's front end shows under python."), "",
             "| Language | Rule | CVE pairs found | Fixed code still flagged | Findings on clean apps (apps) |",
             "|---|---|---|---|---|"]
    for lang, rule in sorted(set(cves) | set(noise), key=lambda k: (k[0], -cves.get(k, [0])[0], k[1])):
        found, still = cves.get((lang, rule), [0, 0])
        where = noise.get((lang, rule), [])
        lines.append(f"| {lang} | `{rule}` | {found} | {still} | {len(where)} ({len(set(where))}) |")
    return "\n".join(lines) + "\n"


def main(argv):
    nightly = Path(argv[0]) if argv else max(p for p in NIGHTLY.glob("20??-??-??") if (p / "apps.txt").exists())
    sys.stdout.write(table(nightly))


if __name__ == "__main__":
    main(sys.argv[1:])
