"""codewatch's public rule catalogue, in two layers.

imported/  Generated by an import (build.py) from the analyzers' metadata and free standards (MITRE CWE, OWASP
           via MITRE, W3C WCAG). Replaced wholesale on every import.
custom/    Maintained by people and never touched by an import: mappings.json (extra CWE/WCAG/OWASP mappings
           and equivalent rules), overrides.json (per-rule severity/type/title/disabled) and rules/*.yml
           (codewatch's own checks, in Semgrep syntax, which run in every scan).

The two are merged whenever the catalogue is loaded. A server's imports go to its cache directory and take
precedence over the snapshot committed in catalog/imported/.
"""
import json
import os
from functools import lru_cache
from pathlib import Path

from .merge import merge

BUNDLED_DIR = Path(__file__).resolve().parents[2] / "catalog"
RUNTIME_DIR = Path(os.environ.get("CODEWATCH_CACHE", Path.home() / ".cache" / "codewatch")) / "catalog"
CUSTOM_DIR = Path(os.environ.get("CODEWATCH_CUSTOM_RULES", BUNDLED_DIR / "custom"))
RULES = "rules"
BUILTIN_RULES_DIR = BUNDLED_DIR / "codewatch" / RULES
ANY = "any"

# Issues whose rule is not a catalogue code: pip-audit names the advisory, detect-secrets the secret type.
ISSUE_RULE_ALIASES = {
    "pip-audit": "pip-audit/vulnerable-dependency",
    "osv": "osv/vulnerable-dependency",
    "detect-secrets": "detect-secrets/hard-coded-secret",  # pragma: allowlist secret
}


def imported_dir():
    runtime = RUNTIME_DIR / "imported"
    return runtime if (runtime / "rules.json").exists() else BUNDLED_DIR / "imported"


def read_json(path, default):
    return json.loads(path.read_text()) if path.exists() else default


def custom_rule_files():
    return sorted((CUSTOM_DIR / RULES).glob("*.y*ml"))


def builtin_rule_files():
    return sorted(BUILTIN_RULES_DIR.glob("*.y*ml"))


def rules_in(path):
    """Rules from one YAML file; a broken file is skipped (and reported) rather than breaking every scan."""
    import sys

    import yaml

    try:
        return (yaml.safe_load(path.read_text()) or {}).get(RULES, [])
    except (OSError, yaml.YAMLError) as exc:
        print(f"codewatch: skipping rule file {path}: {exc}", file=sys.stderr)
        return []


def custom_semgrep_rules():
    """codewatch's built-in and the project's custom Semgrep rules as one config document, for scans.

    Anchors in the rule files are expanded here, so semgrep receives plain YAML.
    """
    import yaml

    class PlainDumper(yaml.SafeDumper):
        def ignore_aliases(self, _data):
            return True

    rules = []
    for path in [*builtin_rule_files(), *custom_rule_files()]:
        rules += rules_in(path)
    return yaml.dump({RULES: rules}, Dumper=PlainDumper, sort_keys=False) if rules else ""


@lru_cache(maxsize=1)
def load():
    base = imported_dir()
    standards = read_json(base / "standards.json", {})
    rules = merge(
        read_json(base / "rules.json", []),
        standards,
        read_json(CUSTOM_DIR / "mappings.json", {}),
        read_json(CUSTOM_DIR / "overrides.json", {}).get(RULES, {}),
        [*((p, "codewatch") for p in builtin_rule_files()), *((p, "custom") for p in custom_rule_files())],
    )
    return rules, standards


@lru_cache(maxsize=1)
def index():
    return {r["id"]: r for r in load()[0]}


@lru_cache(maxsize=1)
def docs():
    return read_json(imported_dir() / "docs.json", {})


def meta():
    return read_json(imported_dir() / "meta.json", {})


def changes():
    return read_json(imported_dir() / "changes.json", {})


def reload():
    for cached in (load, index, docs, bandit_by_test_id):
        cached.cache_clear()


def find(rule_id):
    return index().get(rule_id)


@lru_cache(maxsize=1)
def bandit_by_test_id():
    return {r["id"].split("/", 1)[1].split(":", 1)[0]: r for r in load()[0] if r["id"].startswith("bandit/")}


def lookup(tool, code):
    """Catalogue entry for an issue's tool + rule; bandit issues carry "B105:name", ruff "F841", etc."""
    entry = find(ISSUE_RULE_ALIASES.get(tool) or f"{tool}/{code}")
    if entry is None and tool == "bandit":
        # bandit renames tests between releases (B324:hashlib vs B324:hashlib_insecure_functions); the id is stable.
        entry = bandit_by_test_id().get(code.split(":", 1)[0])
    return entry


def ancestors(cwe, parents):
    seen, stack = set(), [cwe]
    while stack:
        for p in parents.get(str(stack.pop()), []):
            if p not in seen:
                seen.add(p)
                stack.append(p)
    return seen


def expanded_cwes(cwes, parents):
    out = set(cwes)
    for c in cwes:
        out |= ancestors(c, parents)
    return out


def speaks(rule, lang):
    return lang in rule["languages"] or ANY in rule["languages"]


class Coverage:
    """How many rules address each standard entry, per language.

    A rule counts towards a CWE if it targets it or a more specific weakness beneath it.
    """

    def __init__(self, rules, standards):
        self.standards = standards
        parents = standards.get("cwe_parents", {})
        self.covers = [(r, expanded_cwes(r["cwe"], parents)) for r in rules if not r.get("disabled")]

    def count(self, cwes, lang, owasp_id=None):
        return sum(1 for r, exp in self.covers if speaks(r, lang) and (exp & cwes or owasp_id in r["owasp"]))

    def top25(self, languages):
        names = self.standards["cwe_names"]
        return [{"cwe": c, "rank": i + 1, "name": names.get(str(c), ""),
                 "by_language": {lang: self.count({c}, lang) for lang in languages}}
                for i, c in enumerate(self.standards["top25"]["cwes"])]

    def owasp(self, languages):
        return [{**cat, "by_language": {lang: self.count(set(cat["cwes"]), lang, cat["id"]) for lang in languages}}
                for cat in self.standards["owasp"]["categories"]]

    def wcag(self):
        return [{**sc, "rules": sum(1 for r, _ in self.covers if sc["sc"] in r["wcag"])}
                for sc in self.standards.get("wcag", {}).get("criteria", [])]


def coverage(rules, standards, languages):
    c = Coverage(rules, standards)
    return c.top25(languages), c.owasp(languages), c.wcag()
