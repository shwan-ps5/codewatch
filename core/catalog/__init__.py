"""codewatch's public rule catalogue, in two layers.

imported/  Generated by an import (build.py) from the analyzers' metadata and free standards (MITRE CWE, OWASP
           via MITRE, W3C WCAG). Replaced wholesale on every import.
custom/    Maintained by people and never touched by an import: mappings.json (extra CWE/WCAG/OWASP mappings
           and equivalent rules), overrides.json (per-rule severity/type/title/disabled) and rules/*.yml
           (codewatch's own checks, in Semgrep syntax, which run in every scan).

The two are merged whenever the catalogue is loaded. A server's imports go to its cache directory and take
precedence over the snapshot committed in catalog/imported/.
"""
import json
import os
from functools import lru_cache
from pathlib import Path

from .merge import merge

BUNDLED_DIR = Path(__file__).resolve().parents[2] / "catalog"
RUNTIME_DIR = Path(os.environ.get("CODEWATCH_CACHE", Path.home() / ".cache" / "codewatch")) / "catalog"
CUSTOM_DIR = Path(os.environ.get("CODEWATCH_CUSTOM_RULES", BUNDLED_DIR / "custom"))
ANY = "any"

# Issues whose rule is not a catalogue code: pip-audit names the advisory, detect-secrets the secret type.
ISSUE_RULE_ALIASES = {
    "pip-audit": "pip-audit/vulnerable-dependency",
    "detect-secrets": "detect-secrets/hard-coded-secret",
}


def imported_dir():
    runtime = RUNTIME_DIR / "imported"
    return runtime if (runtime / "rules.json").exists() else BUNDLED_DIR / "imported"


def read_json(path, default):
    return json.loads(path.read_text()) if path.exists() else default


def custom_rule_files():
    return sorted((CUSTOM_DIR / "rules").glob("*.y*ml"))


def custom_semgrep_rules():
    """All custom rules as one Semgrep config document, for scans."""
    import yaml

    rules = []
    for path in custom_rule_files():
        rules += (yaml.safe_load(path.read_text()) or {}).get("rules", [])
    return yaml.safe_dump({"rules": rules}, sort_keys=False) if rules else ""


@lru_cache(maxsize=1)
def load():
    base = imported_dir()
    standards = read_json(base / "standards.json", {})
    rules = merge(
        read_json(base / "rules.json", []),
        standards,
        read_json(CUSTOM_DIR / "mappings.json", {}),
        read_json(CUSTOM_DIR / "overrides.json", {}).get("rules", {}),
        custom_rule_files(),
    )
    return rules, standards


@lru_cache(maxsize=1)
def index():
    return {r["id"]: r for r in load()[0]}


@lru_cache(maxsize=1)
def docs():
    return read_json(imported_dir() / "docs.json", {})


def meta():
    return read_json(imported_dir() / "meta.json", {})


def changes():
    return read_json(imported_dir() / "changes.json", {})


def reload():
    for cached in (load, index, docs):
        cached.cache_clear()


def find(rule_id):
    return index().get(rule_id)


def lookup(tool, code):
    """Catalogue entry for an issue's tool + rule; bandit issues carry "B105:name", ruff "F841", etc."""
    return find(ISSUE_RULE_ALIASES.get(tool) or f"{tool}/{code}")


def ancestors(cwe, parents):
    seen, stack = set(), [cwe]
    while stack:
        for p in parents.get(str(stack.pop()), []):
            if p not in seen:
                seen.add(p)
                stack.append(p)
    return seen


def expanded_cwes(cwes, parents):
    out = set(cwes)
    for c in cwes:
        out |= ancestors(c, parents)
    return out


def speaks(rule, lang):
    return lang in rule["languages"] or ANY in rule["languages"]


def coverage(rules, standards, languages):
    """Per Top 25 CWE, OWASP category and WCAG criterion: how many rules address it, per language.

    A rule counts towards a CWE if it targets it or a more specific weakness beneath it.
    """
    parents = standards.get("cwe_parents", {})
    covers = [(r, expanded_cwes(r["cwe"], parents)) for r in rules if not r.get("disabled")]

    def count(cwes, lang, owasp_id=None):
        return sum(1 for r, exp in covers if speaks(r, lang) and (exp & cwes or owasp_id in r["owasp"]))

    top25 = [{"cwe": c, "rank": i + 1, "name": standards["cwe_names"].get(str(c), ""),
              "by_language": {lang: count({c}, lang) for lang in languages}}
             for i, c in enumerate(standards["top25"]["cwes"])]
    owasp = [{**cat, "by_language": {lang: count(set(cat["cwes"]), lang, cat["id"]) for lang in languages}}
             for cat in standards["owasp"]["categories"]]
    wcag = [{**sc, "rules": sum(1 for r, _ in covers if sc["sc"] in r["wcag"])}
            for sc in standards.get("wcag", {}).get("criteria", [])]
    return top25, owasp, wcag
